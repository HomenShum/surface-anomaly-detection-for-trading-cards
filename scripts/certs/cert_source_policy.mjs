import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { certDataDir } from "./cert_reference_lib.mjs";

const SYNTHETIC_PATTERN = /(synthetic|generated_synthetic|auto[-_\s]?generated|gate[-_\s]?unblock|automated gate unblock)/i;

function textBlob(value) {
  if (value == null) return "";
  if (typeof value === "string") return value;
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}

export function isSyntheticReview(review) {
  if (!review) return false;
  return Boolean(review.autoGenerated) || SYNTHETIC_PATTERN.test(textBlob(review));
}

export function isSyntheticReference(ref) {
  if (!ref) return false;
  return (
    Boolean(ref.autoGenerated) ||
    SYNTHETIC_PATTERN.test(textBlob({
      id: ref.id,
      source: ref.source,
      sourceType: ref.sourceType,
      imageEvidenceStatus: ref.imageEvidenceStatus,
      metadataConfidence: ref.metadataConfidence,
      ingestionPolicy: ref.ingestionPolicy,
      autoGeneratedReason: ref.autoGeneratedReason,
      contributorHandle: ref.contributorHandle,
      limitations: ref.limitations,
      warnings: ref.warnings,
      humanDingReview: ref.humanDingReview,
    })) ||
    isSyntheticReview(ref.humanDingReview)
  );
}

export function isSyntheticArtifact(artifact) {
  if (!artifact) return false;
  return (
    Boolean(artifact.autoGenerated) ||
    SYNTHETIC_PATTERN.test(textBlob({
      source: artifact.source,
      sourcePath: artifact.sourcePath,
      sourceType: artifact.sourceType,
      imageEvidenceStatus: artifact.imageEvidenceStatus,
      notes: artifact.notes,
      autoGeneratedReason: artifact.autoGeneratedReason,
    }))
  );
}

export function auditReferencePolicy(ref) {
  const issues = [];
  const syntheticRef = isSyntheticReference(ref);
  if (syntheticRef) {
    issues.push({
      id: `synthetic_reference_${ref.id}`,
      severity: "P0",
      layer: "source_policy",
      certId: ref.id,
      title: "Synthetic/generated reference cannot count toward trust gates",
      detail: `${ref.provider ?? "unknown"} ${ref.certNumber ?? ref.id} contains synthetic or auto-generated source signals.`,
      nextAction: "Keep this row as a demo fixture only, or replace it with user/vendor-provided replayable images and non-generated review evidence.",
    });
  }

  if (ref.provider === "TAG" && ref.hasFrontBackSlabImages && !String(ref.ingestionPolicy ?? "").toLowerCase().includes("user-provided")) {
    issues.push({
      id: `tag_image_policy_${ref.id}`,
      severity: "P0",
      layer: "source_policy",
      certId: ref.id,
      title: "TAG image ingestion must be user-provided or permissioned",
      detail: `${ref.provider} ${ref.certNumber ?? ref.id} declares local slab imagery without a user-provided or permissioned policy note.`,
      nextAction: "Keep TAG records link-only unless screenshots/images are user-provided or there is explicit API/partner permission.",
    });
  }

  return {
    refId: ref.id,
    syntheticRef,
    issues,
  };
}

export function loadSourcePolicyConfig() {
  const path = join(certDataDir(), "source-policy.json");
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf-8"));
  } catch {
    return null;
  }
}
